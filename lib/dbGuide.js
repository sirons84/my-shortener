// 「챗GPT용 복사」 버튼이 클립보드에 넣는 안내문. 챗GPT가 이것만 읽고 연동 코드를 쓸 수 있어야 한다.
// 버전을 붙여 둔다. 책에는 "복사 버튼으로 복사한 문단을 붙인다"로만 쓰고 문단 자체는 싣지 않는다.
export const DB_GUIDE_VERSION = 'v1';

export function buildDbGuideText({ url, key, name }) {
  return [
    `[기록 곳간 연동 안내 ${DB_GUIDE_VERSION}]`,
    `표 이름: ${name}`,
    `표 주소: ${url}`,
    `교사 키: ${key}`,
    '',
    '- 읽기: GET 표주소 → 모든 행이 JSON 배열로 온다. 행마다 row(번호)와 at(시각)이 붙는다. ?since={row}를 붙이면 그 뒤 행만 온다.',
    '- 추가: POST 표주소, 본문은 JSON 객체 하나(Content-Type: application/json). 키 없이 된다. 응답 {"ok":true,"row":23,"at":"2026-10-21T09:30:12+09:00"}',
    '- 고치기: PUT 표주소/{row}, 헤더 X-Oesol-Key: 교사키. 본문으로 행 전체를 바꾼다.',
    '- 지우기: DELETE 표주소/{row}, 같은 헤더.',
    '- 실패하면 {"ok":false,"error":"이유"}가 온다. 화면에 "저장 실패: 이유"를 보여 주고 입력은 지우지 마라.',
    '- 컬럼은 정해져 있지 않다. 객체의 키가 그대로 열 이름이 된다. row와 at은 예약어라 쓰지 마라.',
    '- 행 하나는 2KB(한글 약 600자) 이하. 전화번호·주민번호·생년월일 같은 개인정보는 넣지 마라(서버가 거부한다).',
    '- 학생이 여는 앱이면 읽기와 추가만 쓰고 교사 키를 코드에 넣지 마라. 교사가 고치거나 지워야 하면 교사용 HTML을 따로 한 장 만들고 거기에만 키를 넣어라.',
    '- 주기적으로 읽는 화면은 10초 이상 간격으로, ?since를 써라.',
    '- CORS가 열려 있어 파일로 연 HTML(file://)에서도 fetch가 된다. 결과물은 HTML 한 장으로 만들어라.',
  ].join('\n');
}

